/**
 * Filter stoppages with priority scoring:
 * 1. Prefix match (starts with query)
 * 2. Major hubs matching query
 * 3. Contains match
 */
export function searchStoppages(query: string, maxResults: number = 15): TransitStoppage[] {
  const q = query.trim().toLowerCase();
  if (!q) return ALL_STOPPAGES.filter(s => s.isHub).slice(0, maxResults);

  const prefixMatches: TransitStoppage[] = [];
  const containsMatches: TransitStoppage[] = [];

  for (const stop of ALL_STOPPAGES) {
    const en = stop.nameEn.toLowerCase();
    const bn = stop.nameBn.toLowerCase();

    if (en.startsWith(q) || bn.startsWith(q)) {
      prefixMatches.push(stop);
    } else if (en.includes(q) || bn.includes(q)) {
      containsMatches.push(stop);
    }
  }

  // Sort prefix matches so major hubs appear first
  prefixMatches.sort((a, b) => {
    if (a.isHub && !b.isHub) return -1;
    if (!a.isHub && b.isHub) return 1;
    return a.nameEn.localeCompare(b.nameEn);
  });

  containsMatches.sort((a, b) => {
    if (a.isHub && !b.isHub) return -1;
    if (!a.isHub && b.isHub) return 1;
    return a.nameEn.localeCompare(b.nameEn);
  });

  return [...prefixMatches, ...containsMatches].slice(0, maxResults);
}
